-- 中转助手 - 数据库初始化脚本（扩充版）
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cities (
    id INT AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(10) UNIQUE NOT NULL COMMENT '城市代码',
    name VARCHAR(50) NOT NULL COMMENT '城市名称',
    name_en VARCHAR(50) COMMENT '英文名称',
    country VARCHAR(50) DEFAULT '中国' COMMENT '国家',
    latitude DECIMAL(10, 8) COMMENT '纬度',
    longitude DECIMAL(11, 8) COMMENT '经度',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='城市表';

CREATE TABLE IF NOT EXISTS stations (
    id INT AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(20) UNIQUE NOT NULL COMMENT '站点代码',
    name VARCHAR(100) NOT NULL COMMENT '站点名称',
    name_en VARCHAR(100) COMMENT '英文名称',
    city_code VARCHAR(10) NOT NULL COMMENT '所属城市',
    type ENUM('airport', 'train_station', 'bus_station') NOT NULL COMMENT '站点类型',
    latitude DECIMAL(10, 8) COMMENT '纬度',
    longitude DECIMAL(11, 8) COMMENT '经度',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (city_code) REFERENCES cities(code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='交通站点表';

CREATE TABLE IF NOT EXISTS routes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    from_station VARCHAR(20) NOT NULL COMMENT '出发站点',
    to_station VARCHAR(20) NOT NULL COMMENT '到达站点',
    transport_type ENUM('flight', 'train') NOT NULL COMMENT '交通方式',
    departure_date DATE NOT NULL COMMENT '出发日期',
    departure_time TIME NOT NULL COMMENT '出发时间',
    arrival_date DATE NOT NULL COMMENT '到达日期',
    arrival_time TIME NOT NULL COMMENT '到达时间',
    price DECIMAL(10, 2) NOT NULL COMMENT '价格',
    duration_minutes INT NOT NULL COMMENT '行程时长(分钟)',
    company VARCHAR(50) COMMENT '航空公司/铁路局',
    flight_train_no VARCHAR(20) COMMENT '航班号/车次',
    platform VARCHAR(30) NOT NULL DEFAULT 'ctrip' COMMENT '数据来源平台',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (from_station) REFERENCES stations(code),
    FOREIGN KEY (to_station) REFERENCES stations(code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='路线表';

CREATE TABLE IF NOT EXISTS users (
    id VARCHAR(40) PRIMARY KEY,
    username VARCHAR(80) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT TRUE,
    nickname VARCHAR(80),
    avatar_url VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户表';

CREATE TABLE IF NOT EXISTS auth_tokens (
    token_hash CHAR(64) PRIMARY KEY,
    user_id VARCHAR(40) NOT NULL,
    device_id VARCHAR(40) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NULL,
    revoked_at TIMESTAMP NULL,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='登录令牌表';

CREATE TABLE IF NOT EXISTS user_devices (
    id VARCHAR(40) PRIMARY KEY,
    user_id VARCHAR(40) NOT NULL,
    token_hash CHAR(64),
    device_name VARCHAR(255) NOT NULL,
    ip_address VARCHAR(80) NOT NULL,
    login_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMP NULL,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户登录设备表';

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    email VARCHAR(255) PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    reset_token VARCHAR(120),
    verified_at TIMESTAMP NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='密码重置验证码表';

CREATE TABLE IF NOT EXISTS email_verification_tokens (
    email VARCHAR(255) NOT NULL,
    purpose VARCHAR(40) NOT NULL,
    code VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    verification_token VARCHAR(120),
    verified_at TIMESTAMP NULL,
    PRIMARY KEY (email, purpose)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='閭楠岃瘉鐮佽〃';

CREATE TABLE IF NOT EXISTS user_preferences (
    user_id VARCHAR(40) PRIMARY KEY,
    theme VARCHAR(10) NOT NULL DEFAULT 'light',
    language VARCHAR(10) NOT NULL DEFAULT 'zh',
    search_retention_days INT NOT NULL DEFAULT 30,
    chat_retention_days INT NOT NULL DEFAULT 30,
    import_platforms TEXT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户偏好表';

CREATE TABLE IF NOT EXISTS user_favorites (
    id VARCHAR(40) PRIMARY KEY,
    user_id VARCHAR(40) NOT NULL,
    route_id VARCHAR(255) NOT NULL,
    route_json MEDIUMTEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_user_route (user_id, route_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户收藏路线表';

CREATE TABLE IF NOT EXISTS user_avatars (
    user_id VARCHAR(40) PRIMARY KEY,
    content_type VARCHAR(120) NOT NULL,
    data LONGBLOB NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户头像表';

CREATE TABLE IF NOT EXISTS ai_search_sessions (
    session_id VARCHAR(80) PRIMARY KEY,
    user_id VARCHAR(40) NOT NULL,
    title VARCHAR(120) NOT NULL,
    status VARCHAR(40) NOT NULL,
    last_message_preview VARCHAR(255) NOT NULL,
    response_json MEDIUMTEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI搜索会话表';

CREATE TABLE IF NOT EXISTS bookings (
    booking_id VARCHAR(40) PRIMARY KEY,
    user_id VARCHAR(40) NOT NULL,
    route_id VARCHAR(255) NOT NULL,
    legs_json MEDIUMTEXT NOT NULL,
    status VARCHAR(40) NOT NULL,
    redirect_url VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='预订订单表';

CREATE TABLE IF NOT EXISTS security_audit_logs (
    id VARCHAR(40) PRIMARY KEY,
    user_id VARCHAR(40),
    event_type VARCHAR(80) NOT NULL,
    ip_address VARCHAR(80) NOT NULL,
    device_name VARCHAR(255),
    success BOOLEAN NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    metadata_json TEXT NOT NULL,
    INDEX idx_audit_user_time (user_id, created_at),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='security audit logs';

