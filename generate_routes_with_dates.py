def generate_sql():
    """生成带日期的SQL插入语句"""
    lines = []

    # 飞机路线 - 三天数据
    lines.append("-- ============================================")
    lines.append("-- 插入飞机路线（360条 = 120条基础 x 3天）")
    lines.append("-- ============================================")
    lines.append("INSERT INTO routes (from_station, to_station, transport_type, departure_date, departure_time, arrival_date, arrival_time, price, duration_minutes, company, flight_train_no) VALUES")

    flight_values = []
    for date in DATES:
        for route in FLIGHT_ROUTES:
            from_sta, to_sta, transport, dep_time, arr_time, price, duration, company, flight_no = route
            # 价格浮动 ±10%
            import random
            price_varied = round(price * random.uniform(0.9, 1.1), 2)
            flight_values.append(f"    ('{from_sta}', '{to_sta}', '{transport}', '{date}', '{dep_time}', '{date}', '{arr_time}', {price_varied}, {duration}, '{company}', '{flight_no}')")

    lines.append(",\n".join(flight_values) + ";")

    # 火车路线 - 三天数据
    lines.append("")
    lines.append("-- ============================================")
    lines.append("-- 插入火车路线（450条 = 150条基础 x 3天）")
    lines.append("-- ============================================")
    lines.append("INSERT INTO routes (from_station, to_station, transport_type, departure_date, departure_time, arrival_date, arrival_time, price, duration_minutes, company, flight_train_no) VALUES")

    train_values = []
    for date in DATES:
        for route in TRAIN_ROUTES:
            from_sta, to_sta, transport, dep_time, arr_time, price, duration, company, train_no = route
            # 火车价格基本固定，小幅浮动
            import random
            price_varied = round(price * random.uniform(0.98, 1.02), 2)
            train_values.append(f"    ('{from_sta}', '{to_sta}', '{transport}', '{date}', '{dep_time}', '{date}', '{arr_time}', {price_varied}, {duration}, '{company}', '{train_no}')")

    lines.append(",\n".join(train_values) + ";")

    return "\n".join(lines)


if __name__ == "__main__":
    print(generate_sql())
